import {
  EDGE_BYTES,
  NODE_BYTES,
  OUTPUT_BYTES,
  SOURCE_BYTES,
  type ConnectorPin,
  type ImageEdge,
  type ImageNode,
  type ImageSource,
  type ProgramImage,
} from './image';

/**
 * A `ProgramImage` as a self-contained Arduino sketch.
 *
 * The sketch is a TABLE-DRIVEN interpreter, not one statement per gate. On an
 * Uno that is the difference between fitting and not: 900 unrolled NANDs compile
 * to ~62 KB against a 32 KB ceiling, while the same 900 nodes as 14-byte
 * descriptors plus a ~2 KB interpreter fit with room to spare. The cost is
 * speed, and it is paid only while the circuit is settling, not while the player
 * draws.
 *
 * WHAT THE SKETCH MUST GET RIGHT, and the test that pins each one:
 *
 *  - Storage is sampled for every edge before any edge commits (`tcTick`), so two
 *    memories in series shift one stage per tick instead of racing through both.
 *  - An acyclic circuit is evaluated in dependency order in place; only a circuit
 *    with a combinational cycle pays for a second buffer and Jacobi sweeps, which
 *    is the kernel's own settle rule (`orderNodes` decides which).
 *  - Connector inputs are written into the settle buffer by `tcApplySrc` rather
 *    than poked at one slot in one buffer, so a Jacobi swap cannot lose them.
 *  - `boot` and `reset` publish the storage state before the first sweep, exactly
 *    as `Simulation.reset` does.
 *
 * The line protocol is documented at `protocol.ts`; the sketch half is emitted
 * here because it must stay in step with the arrays it addresses.
 */

/** The serial line protocol's baud rate. */
export const SKETCH_BAUD = 115_200;

/** Longest command line the firmware buffers, including the newline. */
export const SKETCH_LINE_MAX = 48;

export interface SketchOptions {
  /** A name for the header comment and the download filename. */
  readonly name?: string;
}

/** A C++ integer literal for a byte table, `width` per line. */
function bytesLiteral(values: readonly number[], indent: string, perLine = 16): string[] {
  const lines: string[] = [];
  for (let at = 0; at < values.length; at += perLine) {
    const slice = values.slice(at, at + perLine).map((value) => `${value & 0xff}`);
    lines.push(`${indent}${slice.join(',')},`);
  }
  return lines;
}

/** `uint16_t` and `uint8_t` array initialisers, one entry per line for diffing. */
function arrayLiteral<T>(
  values: readonly T[],
  indent: string,
  render: (value: T) => string,
  perLine = 8,
): string[] {
  const lines: string[] = [];
  for (let at = 0; at < values.length; at += perLine) {
    const slice = values.slice(at, at + perLine).map(render);
    lines.push(`${indent}${slice.join(',')},`);
  }
  return lines;
}

/** The four input slots of a node descriptor, zero-padded to the struct's shape. */
function nodeLiteral(
  node: ImageNode,
  tableOffset: number,
  kind: string,
): string {
  const a = node.inputs[0] ?? 0;
  const b = node.inputs[1] ?? 0;
  const c = node.inputs[2] ?? 0;
  const state = node.state < 0 ? 0 : node.state;
  return `{${node.out},${a},${b},${c},${kind},${node.inputs.length},${tableOffset},${state}}`;
}

function edgeLiteral(edge: ImageEdge, tableOffset: number): string {
  const a = edge.inputs[0] ?? 0;
  const b = edge.inputs[1] ?? 0;
  const c = edge.inputs[2] ?? 0;
  return `{${edge.state},${edge.inputs.length},${a},${b},${c},${tableOffset}}`;
}

function sourceLiteral(source: ImageSource): string {
  return `{${source.out},${source.ext},${source.bit}}`;
}

function connectorComment(pins: readonly ConnectorPin[]): string {
  return pins.map((pin) => `${pin.id}[${pin.width}]`).join(' ');
}

/**
 * The sketch text.
 *
 * Deterministic: the lines depend only on the image (node order is already
 * fixed), so two builds of one circuit are byte-identical and a test can check
 * the generator without a snapshot churn on every table tweak.
 */
export function emitSketch(image: ProgramImage, options: SketchOptions = {}): string {
  const name = options.name ?? `tc_${image.level}`;
  const tableOffsets: number[] = [];
  let totalTableBytes = 0;
  for (const table of image.tables) {
    tableOffsets.push(totalTableBytes);
    totalTableBytes += table.length;
  }
  const tableBytes: number[] = [];
  for (const table of image.tables) tableBytes.push(...table);
  const tableLength = Math.max(1, totalTableBytes);
  const slotBytes = Math.max(1, Math.ceil(image.slots / 8));
  const stateCount = Math.max(1, image.stateCount);
  const inputCount = Math.max(1, image.inputs.length);
  const outputCount = Math.max(1, image.outputs.length);
  const nodeCount = Math.max(1, image.nodes.length);
  const sourceCount = Math.max(1, image.sources.length);
  const edgeCount = Math.max(1, image.edges.length);
  const jacobi = image.mode === 'jacobi';

  const lines: string[] = [];
  const push = (...added: string[]): void => {
    lines.push(...added);
  };

  push(
    '/*',
    ' * Generated by turing-complete. Do not edit: regenerate from the sandbox.',
    ` * circuit: ${image.level}`,
    ` * name: ${name}`,
    ` * nodes: ${image.nodes.length}, sources: ${image.sources.length}, edges: ${image.edges.length}`,
    ` * slots: ${image.slots}, state: ${image.stateCount}, mode: ${image.mode}`,
    ` * inputs: ${connectorComment(image.inputs)}`,
    ` * outputs: ${connectorComment(image.outputs)}`,
    ` * estimated RAM: ${image.report.ramBytes} B, estimated flash: ${image.report.flashBytes} B`,
    ' *',
    ' * The board runs the circuit; the game talks to it over the serial lines',
    ' * documented in src/flash/protocol.ts. Type a command and press Enter:',
    ' *   I <connector-index> <value>   set an input connector',
    ' *   T                            one clock edge',
    ' *   R                            clear memory and inputs',
    ' *   C <hz>                       free-run the clock (0 stops it)',
    ' *   S                            print the current frame',
    ' */',
    '#include <Arduino.h>',
    '#include <avr/pgmspace.h>',
    '#include <string.h>',
    '#include <stdlib.h>',
    '',
    `#define TC_BAUD ${SKETCH_BAUD}`,
    `#define TC_LINE_MAX ${SKETCH_LINE_MAX}`,
    `#define TC_MODE_JACOBI ${jacobi ? 1 : 0}`,
    `#define TC_HASH 0x${image.hash.toString(16).toUpperCase().padStart(8, '0')}UL`,
    `#define TC_SLOT_BYTES ${slotBytes}`,
    `#define TC_NODE_COUNT ${image.nodes.length}`,
    `#define TC_SRC_COUNT ${image.sources.length}`,
    `#define TC_EDGE_COUNT ${image.edges.length}`,
    `#define TC_IN_COUNT ${image.inputs.length}`,
    `#define TC_OUT_COUNT ${image.outputs.length}`,
    `#define TC_STATE_COUNT ${image.stateCount}`,
    `#define TC_TABLE_BYTES ${totalTableBytes}`,
    `#define TC_NODE_BYTES ${NODE_BYTES}`,
    `#define TC_EDGE_BYTES ${EDGE_BYTES}`,
    `#define TC_SOURCE_BYTES ${SOURCE_BYTES}`,
    `#define TC_OUTPUT_BYTES ${OUTPUT_BYTES}`,
    '',
    '/** A computed slot: a truth table, a copy, or a stored bit. */',
    'struct TcNode {',
    '  uint16_t out;',
    '  uint16_t a;',
    '  uint16_t b;',
    '  uint16_t c;',
    '  uint8_t kind;',
    '  uint8_t nIn;',
    '  uint16_t table;',
    // The index of the storage element, not its value (that lives one byte per
    // state in TC_STATE): a circuit may hold more than 255 of them.
    '  uint16_t state;',
    '} __attribute__((packed));',
    'enum { TC_TAB, TC_COPY, TC_PUB };',
    '',
    '/** An input connector bit and the slot it writes. */',
    'struct TcSrc {',
    '  uint16_t out;',
    '  uint16_t ext;',
    '  uint8_t bit;',
    '} __attribute__((packed));',
    '',
    '/** One storage element: sample `nIn` input bits, index the transition table. */',
    'struct TcEdge {',
    '  uint16_t state;',
    '  uint8_t nIn;',
    '  uint16_t a;',
    '  uint16_t b;',
    '  uint16_t c;',
    '  uint16_t table;',
    '} __attribute__((packed));',
    '',
    '/* Packed on purpose: the estimate in flash/image.ts is exact only when the',
    '   sizes do not depend on the compiler ABI (AVR aligns uint16_t to one byte,',
    '   a PC compiler to two), and `memcpy_P` copies into these anyway. */',
    'static_assert(sizeof(TcNode) == TC_NODE_BYTES, "update NODE_BYTES in flash/image.ts");',
    'static_assert(sizeof(TcSrc) == TC_SOURCE_BYTES, "update SOURCE_BYTES in flash/image.ts");',
    'static_assert(sizeof(TcEdge) == TC_EDGE_BYTES, "update EDGE_BYTES in flash/image.ts");',
    '',
  );

  // The tables, concatenated. `table` fields hold offsets, not indices.
  push(
    `static const uint8_t TC_TABLES[${tableLength}] PROGMEM = {`,
    ...bytesLiteral(tableBytes, '  '),
    '};',
    '',
    `static const TcNode TC_NODES[${nodeCount}] PROGMEM = {`,
    ...arrayLiteral(
      image.nodes.length === 0 ? [] : image.nodes,
      '  ',
      (node) =>
        nodeLiteral(
          node,
          tableOffsets[node.table] ?? 0,
          node.kind === 'tab' ? 'TC_TAB' : node.kind === 'copy' ? 'TC_COPY' : 'TC_PUB',
        ),
    ),
    ...(image.nodes.length === 0 ? ['  {0,0,0,0,TC_TAB,0,0,0},'] : []),
    '};',
    '',
    `static const TcSrc TC_SRC[${sourceCount}] PROGMEM = {`,
    ...arrayLiteral(image.sources, '  ', sourceLiteral),
    ...(image.sources.length === 0 ? ['  {0,0,0},'] : []),
    '};',
    '',
    `static const TcEdge TC_EDGES[${edgeCount}] PROGMEM = {`,
    ...arrayLiteral(image.edges, '  ', (edge) => edgeLiteral(edge, tableOffsets[edge.table] ?? 0)),
    ...(image.edges.length === 0 ? ['  {0,0,0,0,0,0},'] : []),
    '};',
    '',
    `static const uint16_t TC_OUT_BASE[${outputCount}] PROGMEM = {`,
    ...arrayLiteral(image.outputs, '  ', (pin) => `${pin.base}`),
    ...(image.outputs.length === 0 ? ['  0,'] : []),
    '};',
    `static const uint8_t TC_OUT_WIDTH[${outputCount}] PROGMEM = {`,
    ...arrayLiteral(image.outputs, '  ', (pin) => `${pin.width}`),
    ...(image.outputs.length === 0 ? ['  0,'] : []),
    '};',
    '',
    `static uint8_t TC_S[TC_SLOT_BYTES];`,
  );

  if (jacobi) push(`static uint8_t TC_S2[TC_SLOT_BYTES];`);
  push(
    `static uint8_t *tcCur = TC_S;`,
    ...(jacobi ? ['static uint8_t *tcNext = TC_S2;'] : []),
    `static uint8_t TC_STATE[${stateCount}];`,
    `static uint8_t TC_PENDING[${stateCount}];`,
    `static uint32_t TC_IN[${inputCount}];`,
    'static uint32_t TC_TICK = 0;',
    'static uint8_t TC_STABLE = 1;',
    'static char tcLine[TC_LINE_MAX];',
    'static uint8_t tcLen = 0;',
    'static uint16_t tcClockMs = 0;',
    'static uint32_t tcLastTick = 0;',
    '',
    'static inline uint8_t tcGet(const uint8_t *s, uint16_t i) {',
    '  return (uint8_t)((s[(uint16_t)(i >> 3)] >> (uint8_t)(i & 7)) & 1u);',
    '}',
    '',
    'static inline void tcPut(uint8_t *s, uint16_t i, uint8_t v) {',
    '  uint16_t at = (uint16_t)(i >> 3);',
    '  uint8_t mask = (uint8_t)(1u << (i & 7));',
    '  if (v) s[at] |= mask; else s[at] &= (uint8_t)~mask;',
    '}',
    '',
    'static inline uint8_t tcTable(uint16_t at) {',
    '  return pgm_read_byte(&TC_TABLES[at]);',
    '}',
    '',
    '/* Connector values live outside the settle buffers, so a swap cannot lose',
    '   them; both buffers are written because either can be the next read. */',
    'static void tcApplySrc(void) {',
    '  for (uint16_t k = 0; k < TC_SRC_COUNT; k++) {',
    '    TcSrc s;',
    '    memcpy_P(&s, &TC_SRC[k], sizeof s);',
    '    uint8_t v = (uint8_t)((TC_IN[s.ext] >> s.bit) & 1u);',
    '    tcPut(TC_S, s.out, v);',
    '#if TC_MODE_JACOBI',
    '    tcPut(TC_S2, s.out, v);',
    '#endif',
    '  }',
    '}',
    '',
    '/* In a DAG the caller has already ordered the nodes, so this is in place. */',
    'static void tcSweep(uint8_t *dst) {',
    '  for (uint16_t k = 0; k < TC_NODE_COUNT; k++) {',
    '    TcNode n;',
    '    memcpy_P(&n, &TC_NODES[k], sizeof n);',
    '    uint8_t v;',
    '    if (n.kind == TC_COPY) {',
    '      v = tcGet(tcCur, n.a);',
    '    } else if (n.kind == TC_PUB) {',
    '      v = tcTable((uint16_t)(n.table + TC_STATE[n.state]));',
    '    } else {',
    '      uint16_t idx = tcGet(tcCur, n.a);',
    '      if (n.nIn > 1u) idx = (uint16_t)(idx | (tcGet(tcCur, n.b) << 1));',
    '      if (n.nIn > 2u) idx = (uint16_t)(idx | (tcGet(tcCur, n.c) << 2));',
    '      v = tcTable((uint16_t)(n.table + idx));',
    '    }',
    '    tcPut(dst, n.out, v);',
    '  }',
    '}',
    '',
    'static uint8_t tcSettle(void) {',
    '#if TC_MODE_JACOBI',
    '  for (uint16_t it = 0; it < 512; it++) {',
    '    tcSweep(tcNext);',
    '    if (memcmp(tcCur, tcNext, TC_SLOT_BYTES) == 0) return 1;',
    '    uint8_t *tmp = tcCur;',
    '    tcCur = tcNext;',
    '    tcNext = tmp;',
    '  }',
    '  return 0;',
    '#else',
    '  tcCur = TC_S;',
    '  tcSweep(TC_S);',
    '  return 1;',
    '#endif',
    '}',
    '',
    'static void tcPrintFrame(void) {',
    '  Serial.print(F("F "));',
    '  Serial.print(TC_TICK);',
    '  Serial.print(\' \');',
    '  Serial.print(TC_STABLE ? 1 : 0);',
    '  for (uint16_t i = 0; i < TC_OUT_COUNT; i++) {',
    '    uint16_t base = (uint16_t)pgm_read_word(&TC_OUT_BASE[i]);',
    '    uint8_t width = pgm_read_byte(&TC_OUT_WIDTH[i]);',
    '    uint32_t value = 0;',
    '    for (uint8_t bit = 0; bit < width; bit++) {',
    '      if (tcGet(tcCur, (uint16_t)(base + bit))) value |= ((uint32_t)1u << bit);',
    '    }',
    '    Serial.print(\' \');',
    '    Serial.print(value);',
    '  }',
    '  Serial.println();',
    '}',
    '',
    'static void tcBanner(void) {',
    '  Serial.print(F("#TC1 "));',
    '  Serial.print((uint32_t)TC_HASH, HEX);',
    '  Serial.print(\' \');',
    '  Serial.print(TC_NODE_COUNT);',
    '  Serial.print(\' \');',
    '  Serial.print(TC_SLOT_BYTES);',
    '  Serial.print(\' \');',
    '  Serial.print(TC_IN_COUNT);',
    '  Serial.print(\' \');',
    '  Serial.print(TC_OUT_COUNT);',
    '  Serial.println();',
    '}',
    '',
    'static void tcTick(void) {',
    '  for (uint16_t k = 0; k < TC_EDGE_COUNT; k++) {',
    '    TcEdge e;',
    '    memcpy_P(&e, &TC_EDGES[k], sizeof e);',
    '    uint16_t idx = tcGet(tcCur, e.a);',
    '    if (e.nIn > 1u) idx = (uint16_t)(idx | (tcGet(tcCur, e.b) << 1));',
    '    if (e.nIn > 2u) idx = (uint16_t)(idx | (tcGet(tcCur, e.c) << 2));',
    '    uint16_t at = (uint16_t)(e.table + (uint16_t)TC_STATE[e.state] * (uint16_t)(1u << e.nIn) + idx);',
    '    TC_PENDING[e.state] = pgm_read_byte(&TC_TABLES[at]);',
    '  }',
    '  for (uint16_t k = 0; k < TC_EDGE_COUNT; k++) {',
    '    TcEdge e;',
    '    memcpy_P(&e, &TC_EDGES[k], sizeof e);',
    '    TC_STATE[e.state] = TC_PENDING[e.state];',
    '  }',
    '  TC_TICK++;',
    '  TC_STABLE = tcSettle();',
    '  tcPrintFrame();',
    '}',
    '',
    'static void tcReset(void) {',
    '  memset(TC_S, 0, sizeof TC_S);',
    '#if TC_MODE_JACOBI',
    '  memset(TC_S2, 0, sizeof TC_S2);',
    '  tcCur = TC_S;',
    '  tcNext = TC_S2;',
    '#endif',
    '  memset(TC_STATE, 0, sizeof TC_STATE);',
    '  for (uint16_t i = 0; i < TC_IN_COUNT; i++) TC_IN[i] = 0;',
    '  TC_TICK = 0;',
    '  tcApplySrc();',
    '  TC_STABLE = tcSettle();',
    '  tcPrintFrame();',
    '}',
    '',
    'static void tcSetInput(uint16_t index, uint32_t value) {',
    '  if (index >= TC_IN_COUNT) return;',
    '  TC_IN[index] = value;',
    '  tcApplySrc();',
    '  TC_STABLE = tcSettle();',
    '  tcPrintFrame();',
    '}',
    '',
    'static void tcSetClock(uint16_t hz) {',
    '  tcClockMs = hz == 0 ? 0 : (uint16_t)(1000u / hz);',
    '  tcLastTick = millis();',
    '}',
    '',
    'static void tcHandleLine(char *line) {',
    '  if (line[0] == \'I\' && line[1] == \' \') {',
    '    char *p = line + 2;',
    '    uint16_t index = (uint16_t)strtoul(p, &p, 10);',
    '    while (*p == \' \') p++;',
    '    uint32_t value = strtoul(p, NULL, 10);',
    '    tcSetInput(index, value);',
    '    return;',
    '  }',
    '  if (strcmp(line, "T") == 0) { tcTick(); return; }',
    '  if (strcmp(line, "R") == 0) { tcReset(); return; }',
    '  if (strcmp(line, "S") == 0) { tcPrintFrame(); return; }',
    '  if (strcmp(line, "B") == 0) { tcBanner(); return; }',
    '  if (line[0] == \'C\' && line[1] == \' \') {',
    '    tcSetClock((uint16_t)strtoul(line + 2, NULL, 10));',
    '    return;',
    '  }',
    '}',
    '',
    'void setup() {',
    '  Serial.begin(TC_BAUD);',
    '  for (uint16_t i = 0; i < TC_IN_COUNT; i++) TC_IN[i] = 0;',
    '  tcApplySrc();',
    '  TC_STABLE = tcSettle();',
    '  tcBanner();',
    '  tcPrintFrame();',
    '}',
    '',
    'void loop() {',
    '  while (Serial.available() > 0) {',
    '    char c = (char)Serial.read();',
    '    if (c == \'\\n\') {',
    '      tcLine[tcLen] = \'\\0\';',
    '      if (tcLen > 0) tcHandleLine(tcLine);',
    '      tcLen = 0;',
    '    } else if (c != \'\\r\' && tcLen < TC_LINE_MAX - 1) {',
    '      tcLine[tcLen++] = c;',
    '    }',
    '  }',
    '  if (tcClockMs > 0 && (uint32_t)(millis() - tcLastTick) >= tcClockMs) {',
    '    tcLastTick = millis();',
    '    tcTick();',
    '  }',
    '}',
    '',
  );

  return `${lines.join('\n')}`;
}
